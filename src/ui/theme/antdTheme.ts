import { theme as antdTheme, type ThemeConfig } from 'antd';
import { fonts, palette, radius, type Mode } from './tokens';

/** Ant Design theme for both modes, mirroring the CSS variables in styles/tokens.css. */
export function buildAntdTheme(mode: Mode, large: boolean): ThemeConfig {
  const c = palette[mode];
  const dark = mode === 'dark';
  const fontSize = large ? 15 : 14;
  return {
    algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    cssVar: true,
    hashed: false,
    token: {
      colorPrimary: c.primary,
      colorSuccess: c.success,
      colorWarning: c.warning,
      colorError: c.danger,
      colorInfo: c.info,
      colorLink: c.primary,
      colorLinkHover: c.primaryHover,
      colorText: c.text,
      colorTextHeading: c.text,
      colorTextSecondary: c.textSecondary,
      colorTextTertiary: c.textMuted,
      colorTextQuaternary: c.textFaint,
      colorTextPlaceholder: c.textFaint,
      colorTextLightSolid: c.onPrimary,
      colorBorder: c.border,
      colorBorderSecondary: c.borderSubtle,
      colorSplit: c.borderSubtle,
      colorBgLayout: c.bgSubtle,
      colorBgContainer: c.surface,
      colorBgElevated: c.elevated,
      colorBgSpotlight: dark ? '#2a2a2a' : '#0d0d0d',
      colorFillSecondary: dark ? 'rgba(255,255,255,0.08)' : '#efefef',
      colorFillTertiary: dark ? 'rgba(255,255,255,0.05)' : '#f4f4f4',
      colorFillQuaternary: dark ? 'rgba(255,255,255,0.03)' : '#f8f8f8',
      fontFamily: fonts.sans,
      fontFamilyCode: fonts.mono,
      fontSize,
      fontSizeSM: fontSize - 1,
      fontSizeLG: fontSize + 1,
      lineHeight: 1.55,
      borderRadius: radius.md,
      borderRadiusLG: radius.lg,
      borderRadiusSM: radius.sm,
      borderRadiusXS: 6,
      controlHeight: 38,
      controlHeightSM: 30,
      controlHeightLG: 44,
      controlOutline: dark ? 'rgba(255,255,255,0.16)' : 'rgba(0,0,0,0.08)',
      controlOutlineWidth: 3,
      boxShadow: dark ? '0 2px 12px rgba(0,0,0,0.4)' : '0 2px 12px rgba(0,0,0,0.06)',
      boxShadowSecondary: dark ? '0 12px 40px rgba(0,0,0,0.6)' : '0 12px 40px rgba(0,0,0,0.12)',
      motionDurationFast: '0.1s',
      motionDurationMid: '0.16s',
      motionDurationSlow: '0.24s',
      wireframe: false,
    },
    components: {
      Button: {
        fontWeight: 550,
        borderRadius: radius.pill,
        borderRadiusSM: radius.pill,
        borderRadiusLG: radius.pill,
        primaryShadow: 'none',
        defaultShadow: 'none',
        dangerShadow: 'none',
        paddingInline: 16,
        defaultBorderColor: c.border,
        defaultBg: c.surface,
      },
      Input: { activeShadow: 'none', activeBorderColor: dark ? 'rgba(255,255,255,0.4)' : 'rgba(0,0,0,0.35)', hoverBorderColor: dark ? 'rgba(255,255,255,0.24)' : 'rgba(0,0,0,0.2)', paddingInline: 12 },
      InputNumber: { activeShadow: 'none' },
      Select: {
        optionSelectedBg: c.primarySoft,
        optionSelectedColor: c.text,
        optionSelectedFontWeight: 600,
        optionPadding: '8px 12px',
        optionHeight: 36,
      },
      Segmented: {
        trackBg: dark ? 'rgba(255,255,255,0.06)' : '#efefef',
        itemSelectedBg: dark ? '#333333' : '#ffffff',
        itemSelectedColor: c.text,
        itemColor: c.textMuted,
        itemHoverColor: c.text,
        trackPadding: 3,
      },
      Switch: { trackHeight: 22, handleSize: 18, trackMinWidth: 40 },
      Tooltip: { fontSize: 12.5, borderRadius: 8, paddingSM: 10 },
      Dropdown: { paddingBlock: 6, borderRadiusLG: 14 },
      Drawer: { footerPaddingBlock: 14, footerPaddingInline: 20, colorBgElevated: dark ? '#1a1a1a' : '#ffffff' },
      Modal: { borderRadiusLG: radius.xl, contentBg: c.elevated, headerBg: c.elevated, footerBg: 'transparent' },
      Tag: { borderRadiusSM: 999 },
      Slider: { handleColor: c.primary, trackBg: c.primary, trackHoverBg: c.primaryHover },
      Checkbox: { borderRadiusSM: 5 },
      Message: { contentBg: c.elevated },
      Collapse: { headerPadding: '10px 12px', contentPadding: '4px 12px 12px' },
      Tabs: { inkBarColor: c.text, itemSelectedColor: c.text, itemHoverColor: c.text, itemActiveColor: c.text },
    },
  };
}
